#!/bin/bash
# Installs BillFlow as a Mac app plus a recurring launch agent.
#
#   npm run app:install
#
# Safe to re-run -- that is how you apply changes to schedule.conf, or repoint
# everything after moving the project folder.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
APP_NAME="BillFlow"
APP_DIR="$HOME/Applications/$APP_NAME.app"
AGENT_LABEL="com.billflow.scheduled-launch"
AGENT_PLIST="$HOME/Library/LaunchAgents/$AGENT_LABEL.plist"
SERVER_LABEL="com.billflow.server"
SERVER_PLIST="$HOME/Library/LaunchAgents/$SERVER_LABEL.plist"

say() { printf '  %s\n' "$*"; }

echo "Installing $APP_NAME"
say "project: $PROJECT_DIR"

# --- 1. Record absolute tool paths ----------------------------------------
# Finder and launchd start processes with a minimal PATH, so nvm's node and
# Homebrew are both invisible unless we pin them now.
NODE_BIN="$(command -v node || true)"
[ -n "$NODE_BIN" ] || { echo "node is not on PATH; run this from a normal terminal" >&2; exit 1; }
BREW_BIN="$(command -v brew || true)"
PG_ISREADY="$(command -v pg_isready || true)"
if [ -z "$PG_ISREADY" ] && [ -n "$BREW_BIN" ]; then
  for candidate in "$($BREW_BIN --prefix 2>/dev/null)"/opt/postgresql@*/bin/pg_isready; do
    [ -x "$candidate" ] && PG_ISREADY="$candidate" && break
  done
fi
PG_FORMULA="$([ -n "$BREW_BIN" ] && "$BREW_BIN" list --formula 2>/dev/null | grep -m1 '^postgresql@' || true)"

cat > "$SCRIPT_DIR/.runtime.env" <<ENV
# Generated by install.sh -- do not edit by hand, re-run npm run app:install.
NODE_BIN="$NODE_BIN"
BREW_BIN="$BREW_BIN"
PG_ISREADY="$PG_ISREADY"
PG_FORMULA="${PG_FORMULA:-postgresql@16}"
ENV
say "node: $NODE_BIN"
say "postgres: ${PG_FORMULA:-not detected}"

# --- 2. Build the .app bundle ---------------------------------------------
rm -rf "$APP_DIR"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources"

cat > "$APP_DIR/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$APP_NAME</string>
  <key>CFBundleDisplayName</key><string>$APP_NAME</string>
  <key>CFBundleIdentifier</key><string>com.billflow.app</string>
  <key>CFBundleExecutable</key><string>$APP_NAME</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0.0</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

cat > "$APP_DIR/Contents/MacOS/$APP_NAME" <<STUB
#!/bin/bash
exec "$SCRIPT_DIR/launch.sh"
STUB
chmod +x "$APP_DIR/Contents/MacOS/$APP_NAME"

# Icon from the app's own favicon.
ICON_SRC="$PROJECT_DIR/client/public/favicon.png"
if [ -f "$ICON_SRC" ] && command -v iconutil >/dev/null 2>&1; then
  ICONSET="$(mktemp -d)/AppIcon.iconset"
  mkdir -p "$ICONSET"
  for size in 16 32 64 128 256 512; do
    sips -z $size $size "$ICON_SRC" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null 2>&1
    double=$((size * 2))
    sips -z $double $double "$ICON_SRC" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null 2>&1
  done
  iconutil -c icns "$ICONSET" -o "$APP_DIR/Contents/Resources/AppIcon.icns" 2>/dev/null || true
  rm -rf "$(dirname "$ICONSET")"
fi
say "app: $APP_DIR"

# --- 3. Server agent ------------------------------------------------------
# macOS 27 reaps an app bundle's child processes when the bundle's own process
# exits, so a backgrounded server died a second after the .app opened the
# browser. launchd owns the server instead: it starts at login, restarts on
# crash, and the .app simply points a browser at it.
mkdir -p "$HOME/Library/LaunchAgents"
cat > "$SERVER_PLIST" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$SERVER_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$NODE_BIN</string>
    <string>$PROJECT_DIR/dist/index.cjs</string>
  </array>
  <key>WorkingDirectory</key><string>$PROJECT_DIR</string>
  <key>EnvironmentVariables</key>
  <dict><key>NODE_ENV</key><string>production</string></dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/BillFlow-server.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/BillFlow-server.log</string>
</dict>
</plist>
PLIST

launchctl bootout "gui/$(id -u)/$SERVER_LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$SERVER_PLIST"
say "server: always on, managed by launchd"

# --- 4. Schedule ----------------------------------------------------------
# shellcheck disable=SC1091
source "$SCRIPT_DIR/schedule.conf"
INTERVAL_WEEKS="${INTERVAL_WEEKS:-2}"
LAUNCH_TIME="${LAUNCH_TIME:-14:30}"

date -j -f "%Y-%m-%d" "$ANCHOR_DATE" "+%s" >/dev/null 2>&1 \
  || { echo "ANCHOR_DATE='$ANCHOR_DATE' is not a valid YYYY-MM-DD date" >&2; exit 1; }

# launchd fires on a weekday; scheduled-run.sh decides if it is an "on" week.
WEEKDAY="$(date -j -f "%Y-%m-%d" "$ANCHOR_DATE" "+%w")"
WEEKDAY_NAME="$(date -j -f "%Y-%m-%d" "$ANCHOR_DATE" "+%A")"
HOUR="$(echo "$LAUNCH_TIME" | cut -d: -f1 | sed 's/^0//')"
MINUTE="$(echo "$LAUNCH_TIME" | cut -d: -f2 | sed 's/^0//')"

mkdir -p "$HOME/Library/LaunchAgents"
cat > "$AGENT_PLIST" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$AGENT_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>$SCRIPT_DIR/scheduled-run.sh</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Weekday</key><integer>$WEEKDAY</integer>
    <key>Hour</key><integer>${HOUR:-0}</integer>
    <key>Minute</key><integer>${MINUTE:-0}</integer>
  </dict>
  <!-- When a job's main process exits, launchd SIGKILLs everything left in its
       process group. Without this the server we just started dies moments
       later and the browser opens onto a dead port. -->
  <key>AbandonProcessGroup</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/BillFlow.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/BillFlow.log</string>
</dict>
</plist>
PLIST

UID_NUM="$(id -u)"
launchctl bootout "gui/$UID_NUM/$AGENT_LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$UID_NUM" "$AGENT_PLIST"
say "agent: every ${INTERVAL_WEEKS}nd $WEEKDAY_NAME at $LAUNCH_TIME, counting from $ANCHOR_DATE"

echo
echo "Done. Next few scheduled launches:"
"$SCRIPT_DIR/next-runs.sh" 2>/dev/null || true
echo
echo "Open it now:  open -a $APP_NAME"
echo "Change when:  edit script/macos/schedule.conf, then npm run app:install"
